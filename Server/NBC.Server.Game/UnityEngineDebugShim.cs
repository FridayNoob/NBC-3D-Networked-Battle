//
//  ---------------------------------------------------------------------------
//  为什么这里可以用垫片（而不是"那就别复用了"）
//  ---------------------------------------------------------------------------
//  关键是分清两件事：
//      · **碰引擎对象**（`GameObject` / `Transform` / `NavMesh`）→ 必须有引擎运行时 → 进不了服务端（D14 的结论）
//      · **只调一句静态日志**（`Debug.LogWarning`）→ 服务端**不需要**引擎运行时，只要编译期有个同名方法
//  所以这里垫一个 **10 行的 `Debug`**，让整条链编得过；运行时它是空实现（服务端的日志走自己的 `Note` 事件）。
