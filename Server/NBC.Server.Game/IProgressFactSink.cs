// ============================================================================
//  IProgressFactSink —— 「战斗事实」的消费者接缝（M4-S3 §二十五）
//  项目：3D联网战斗Demo
//
//  ---------------------------------------------------------------------------
//  一、为什么要有这道缝（而不是再加一个属性）
//  ---------------------------------------------------------------------------
//  在此之前 `RoomBattleService` 只有一个消费者属性：
//      public AchievementAuthority? Achievements { get; set; }
//  任务权威需要**同一批事实**（击杀/拾取），于是有两种写法：
//
//      ❌ 再加一个属性 `Quests`，然后在 `ApplyProgressFacts` 里写两遍 `ApplyFact`：
//         每加一个消费者（战绩统计、每日任务、活动……）就要**再改一次**
//         `RoomBattleService`，而且很容易漏掉一处 —— 漏了的表现是"某个系统**永远**不涨"，
//         日志全绿。
//
//      ✅ 抽一道缝：消费者**自己注册**，`RoomBattleService` 只负责
//         "把事实从战斗里取一次、喂给所有注册者"。加消费者**不用改这个类**。
//
//  ---------------------------------------------------------------------------
//  二、⚠️ 两个刻意的取舍
//  ---------------------------------------------------------------------------
//  ① **事实只从战斗里取一次**（`CopyPendingFacts` 只调一次），然后分发给所有消费者：
//     这样"谁先看到"不影响"取到了什么"，与 M3-A 那条"一处规则、两个调用点"同一个判据。
//  ② **一个消费者都没有时，事实直接丢掉**（与改造前 `Achievements == null` 的行为一致）：
//     有意的 —— 权威不存在 = 没有记账的地方。`AchievementAuthority` 那边**不会**
//     因此报"没人认领"（那类告警只对"接了权威却没追踪这个玩家"报）。
//
//  ---------------------------------------------------------------------------
//  三、实现者
//  ---------------------------------------------------------------------------
//      `AchievementAuthority`（§二十一）  —— 成就权威
//      `QuestAuthority`（§二十五）        —— 任务权威
//  两者都**已经有** `ApplyFact(in ProgressFact)`，所以只是把它声明出来（零行为改动）。
// ============================================================================

namespace NBC.Server.Game
{
    /// <summary>吃"战斗事实"的东西（成就权威、任务权威……）。</summary>
    public interface IProgressFactSink
    {
        /// <summary>
        /// 消费一条事实。
        /// <para>⚠️ 实现**必须**自己处理"这个玩家没被追踪"（`AchievementAuthority` /
        /// `QuestAuthority` 都是静默跳过并记一次告警）—— 分发方**不做**这层判断，
        /// 否则每个消费者都要在分发方那里加一条特例。</para>
        /// </summary>
        /// <param name="fact">事实。</param>
        void ApplyFact(in ProgressFact fact);
    }
}
