// ============================================================================
//  IPlayerSlotProvider —— 「这次连接该用哪个玩家档案」的接缝
//  项目：3D联网战斗Demo   对应：SRV-06 的最小可用版、`Docs\27` §14.2 的欠账
//
//  ---------------------------------------------------------------------------
//  它解决一个**会咬人**的欠账
//  ---------------------------------------------------------------------------
//  `ServerMessageRouter` 原来是这么分配玩家编号的：
//
//      session.PlayerId = _nextPlayerId++;      // 第 1、2、3… 个连上来的
//
//  而 `battle_player_detail.player_id` 有**外键**指向 `player_profile`（只种了 1~4）。
//  ⇒ **第 5 次连接**拿到的 id 是 5 ⇒ 外键拒绝 ⇒ 那一局的战绩明细**静默被跳过**
//     （表现是"打完一局，`total_kill` 不涨了"）。
//  ⚠️ 而那个计数器**只增不减**：不是"最多 4 个人"，而是"**累计连过 4 次之后就开始丢**"。
//     调试时反复开关窗口很容易撞上。
//
//  ---------------------------------------------------------------------------
//  做法：把"会话"绑到**一个真实的空档案槽位**（断开就还回去）
//  ---------------------------------------------------------------------------
//      · 启动时把 `player_profile.player_id` 全部读进内存（一次查询）
//      · 每次握手**领一个空闲槽位**；断开时**还回去**
//      ⇒ 反复连接会**复用** 1~4，而不是一路涨到 5、6、7…
//
//  ⚠️ **这不是账号系统**：谁连上来都能领到 `测试玩家一`。它只是让"玩家编号"
//     重新**落在一个真实存在的档案上**，从而让战绩写得进去。
//     真正的 SRV-06（登录 → 校验用户名密码 → 绑定 account）做完时，
//     这个接缝的实现换成"按账号查"，**调用方一行都不用改**。
//
//  ---------------------------------------------------------------------------
//  ⚠️ 为什么接缝住在 `NBC.Server.Core`（而不是 `Data`）
//  ---------------------------------------------------------------------------
//  用它的地方是 `ServerMessageRouter`（在 Core）。如果让 Core 直接认
//  `Data` 里的实现，依赖方向就反了（`Core → Data`）—— 而数据库**不该**出现在
//  网络层的视野里（`_net-probe` 要在**没有数据库**的环境里跑 93 条用例）。
//  ⇒ Core **声明**接缝，`Data` **实现**它，**组合根**（Host）把它们接起来。
//     这与 `IAssetProvider` / `ITransport` / `IConditionProgressStore` 是同一个套路。
//
//  ⚠️ **没接实现时（null）必须退回老行为**：`_net-probe` 里没有任何数据库，
//     而它的用例断言 `PlayerId == 1`、`== 2` ⇒ 降级路径要**保持原样**，否则那 93 条会红。
// ============================================================================

namespace NBC.Server.Core
{
    /// <summary>玩家档案槽位的来源（见文件头：它让"玩家编号"落在一个**真实存在的档案**上）。</summary>
    public interface IPlayerSlotProvider
    {
        /// <summary>
        /// 领一个空闲档案。**没有空闲的要返回 false**（调用方降级）。
        /// </summary>
        /// <param name="playerId">领到的玩家编号（`player_profile.player_id`）。</param>
        /// <returns>领到了返回 true。</returns>
        bool TryClaim(out long playerId);

        /// <summary>把档案还回去（会话断开时调）。</summary>
        /// <param name="playerId">要还的玩家编号（≤ 0 或不是这里发出去的要无害）。</param>
        void Release(long playerId);

        /// <summary>一句人话（启动横幅/统计行用）。</summary>
        /// <returns>例如 `档案槽位 1/4 占用（累计发放 6 次）`。</returns>
        string Describe();
    }
}
