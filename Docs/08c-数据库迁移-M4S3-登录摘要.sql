-- ============================================================================
--  数据库迁移：M4-S3 登录摘要配方（2026-09-27）
--  项目：3D联网战斗Demo   对应：`Docs\27` §十九、`Docs\08` 末尾的种子数据说明
--
--  ---------------------------------------------------------------------------
--  这个脚本干什么
--  ---------------------------------------------------------------------------
--  把 4 个测试账号的 `password_hash` 从**旧配方**换成**新配方**：
--      旧（作废）：SHA256( salt + 明文密码 )
--      新（当前）：SHA256( salt + SHA256(明文密码) )
--  密码**没变**，还是 `123456` —— 变的只是"怎么算这个摘要"。
--
--  为什么要改：客户端现在先算一次摘要再上线（**明文密码不再过网络**），
--  服务端再把这个摘要叠上 salt 入库。取舍与"没做到的部分"写在 `Docs\27` §19.2。
--
--  ---------------------------------------------------------------------------
--  ⚠️ 为什么是 UPDATE 而不是 DROP 重建
--  ---------------------------------------------------------------------------
--  `Docs\08-数据库脚本.sql` 是**全新建库**用的，它第 38 行有 `DROP DATABASE`
--  —— 在一台已经有战绩/档案的机器上跑它 = **把数据删了**。
--  已经建过库的机器要跑的是**这个文件**（幂等、只改这一列、不碰别的表）。
--
--  ⚠️ 幂等性：把新值再写一遍没有任何副作用（结果相同），所以重复执行是安全的。
--     但它**不能**判断"现在到底是哪一版配方" —— 所以它不写条件，
--     直接按账号名把新值写上（4 行，都是种子账号）。
--
--  ⚠️ 如果你自己造过账号：这个脚本**不会**动它们。
--     那些账号要用 `Docs\08` 里的新配方重算，或者干脆删掉重建。
--     （服务端的阳性对照只盯 `username LIKE 'test%'`，其余账号它不管 —— 见 `_db-probe`【八】）
--
--  ---------------------------------------------------------------------------
--  怎么确认改对了（**别只看"0 rows affected"就当成功**）
--  ---------------------------------------------------------------------------
--  `UPDATE` 影响 0 行也可能是"写成新值了但本来就是这个值"，也可能是"没有这个账号"。
--  真正的判据是**跑一遍服务端探针**，它会自己算一遍摘要与这 4 行对账：
--      dotnet run --project Server\_db-probe\DbProbe.csproj -m:1
--  看到【八】里那条"阳性对照"是 ✅ 才算改对了。
-- ============================================================================

USE `nbc_db`;

UPDATE `account` SET `password_hash` = 'c4824c4da76bcaf8c29971c8750bced3f13ea8fbd2eedd3d79c9830aaa56abc8'
WHERE `username` = 'test01';

UPDATE `account` SET `password_hash` = '7b4a038dd8f330b253812717d9924ffbacbda23cb83b1749b1f6e1966e3115c4'
WHERE `username` = 'test02';

UPDATE `account` SET `password_hash` = 'cc8f69f2861d3ac681fc8bcab8450e0ff606476f2e724f9920fc029f1f223dd1'
WHERE `username` = 'test03';

UPDATE `account` SET `password_hash` = '3d5bdce083bcd09ac0c58c44f41103d7471b90cd11bae8346987e6b162ed5a8e'
WHERE `username` = 'test04';

-- ---------------------------------------------------------------------------
--  验证查询（执行后人工确认：4 行都要在，且 hash 与上面 4 个值逐字符相同）
-- ---------------------------------------------------------------------------
SELECT `account_id`, `username`, `password_hash`, `salt`
FROM `account`
WHERE `username` LIKE 'test%'
ORDER BY `account_id`;
