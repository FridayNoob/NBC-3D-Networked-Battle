// ============================================================================
//  IQuestRewardSink —— 「奖励到底怎么发下去」的接缝
//  项目：3D联网战斗Demo   对应：M2-A2、M4（服务端权威）
//
//  ---------------------------------------------------------------------------
//  为什么要这一道缝
//  ---------------------------------------------------------------------------
//  任务运行时该负责的是"**该不该发**"（条件满足、状态正确），
//  **不该**负责"经验加到哪个字段、物品进哪个背包格" —— 那是角色/背包模块的事。
//
//  而且到 M4，"发奖励"这件事的正确位置会**移到服务端**（客户端自己加经验 = 作弊）。
//  留一道缝之后，那次迁移只是**换一个实现**：
//
//      M2：InMemoryQuestRewardSink（本地记一下，能演示、能断言）
//      M4：ServerQuestRewardSink（发一条协议，等服务器回执）
//
//  ⚠️ 接口只收 `QuestReward`（一个**中性结构体**），不收配置表生成类型 ——
//     发奖方不该被迫认识 `Config_Reward`。这层映射刻意留在 `QuestRuntime` 里，
//     于是"奖励表的字段变了"只会影响**一个文件**。
//
//  ⚠️ 实现**不应该**在这里抛异常来拒绝发奖：
//     能走到这里，说明"该不该发"已经判断完了。运行时抛异常会让玩家
//     卡在"任务已交付但奖励没到"的中间态。要拒绝就在 `QuestRuntime` 前面拒绝。
// ============================================================================

namespace NBC.Game.Quest
{
    /// <summary>发奖励的地方（经验/金币/物品真正落到谁身上，由实现决定）。</summary>
    public interface IQuestRewardSink
    {
        /// <summary>把一份奖励发下去。</summary>
        /// <param name="questId">任务编号（实现方记日志/埋点用）。</param>
        /// <param name="reward">奖励内容。</param>
        void Grant(int questId, QuestReward reward);
    }
}
