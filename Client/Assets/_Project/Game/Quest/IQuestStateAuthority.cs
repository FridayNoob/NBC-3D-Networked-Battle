// ============================================================================
//  IQuestStateAuthority —— 「这个任务到哪一步了」的权威接缝（M4-S3 §二十六）
//  项目：3D联网战斗Demo
//
//  ---------------------------------------------------------------------------
//  一、⚠️ 它与 `IQuestProgressAuthority` **并排、不合并**（刻意的）
//  ---------------------------------------------------------------------------
//      `IQuestProgressAuthority` = "**某个条件**累计了多少"（任务与成就**共用**那一套）
//      `IQuestStateAuthority`    = "**某个任务**到哪一步了"（**只有任务**有状态机）
//
//  合成一道缝的诱惑很大（都是"问服务端要个数字"），但两者的**生命周期与失败方式**不同：
//      · 条件进度**只增不减**，缺了就是"还没同步"
//      · 任务状态**可以往回退**（服务端说没接过 ⇒ 回到未接取），而且**有两个字段**
//        （状态 + "服务端到底说没说"）—— 混在一起正是 §二十四 那条 null≠0 的坑
//  所以：**分开两道缝**，各有一条"null ≠ 0"的用例盯着。
//
//  ---------------------------------------------------------------------------
//  二、⚠️ 接口故意只有 `TryGetState`：**"服务端没说"必须能被表达出来**
//  ---------------------------------------------------------------------------
//  返回 **false** = **服务端没说**（还没收到过同步）—— **不是**"未接取"。
//  返回 **true + state = 0** = 服务端**明确**说"这个任务没接过"。
//
//      ❌ 把 false 当成 0：玩家刚进游戏、还没同步，界面就把"未接取"画成事实
//      ✅ 正确做法：退回本地那份并标「（本地预测）」（见 `QuestPanelModel`）
//
//  这条与 §二十四 的 `IQuestProgressAuthority` 是**同一条纪律**，理由也一样。
// ============================================================================

namespace NBC.Game.Quest
{
    /// <summary>「这个任务到哪一步了」的权威来源。</summary>
    public interface IQuestStateAuthority
    {
        /// <summary>
        /// 取一个任务的**权威状态**。
        /// <para>⚠️ 返回 **false = 服务端没说**，**不是**"未接取"（见文件头二）。
        /// 实现**不许**在拿不到数据时编一个 0 出来。</para>
        /// </summary>
        /// <param name="questId">任务编号。</param>
        /// <param name="state">状态数字（与 `EQuestState` 一致：0=未接取 1=已接 2=已完成 3=已交付）。</param>
        /// <returns>服务端**确实表态过**这个任务时返回 true。</returns>
        bool TryGetState(int questId, out int state);
    }
}
