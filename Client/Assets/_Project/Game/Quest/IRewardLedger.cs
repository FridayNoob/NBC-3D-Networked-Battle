// ============================================================================
//  IRewardLedger —— 「这份奖励发过没有」的台账接缝
//  项目：3D联网战斗Demo   对应：M4-S3（持久化）、`Docs\27` §11.5
//
//  ---------------------------------------------------------------------------
//  它解决一个**加了持久化之后才出现**的 bug
//  ---------------------------------------------------------------------------
//  成就用 `resetProgress: false` 登记条件，而 `ConditionTracker` 的语义②是
//  **"注册时若已达成，当场回调一次"** —— 这正是"上次已经打了 10 只、这次登录就该解锁"
//  要的行为（M4-S2 的 `AchievementRuntime` 文件头写清了这件事）。
//
//  但把进度落库之后，那个行为**每一步都成立、结果是错的**：
//
//      服务端重启 → `LoadAsync()` 读回"条件已达成" → 构造时 `Register` 当场回调
//                 → `Evaluate` 判定"全部条件都满" → `Unlock` → **再发一次奖**
//
//      ⇒ 每重启一次，所有已完成的成就**再发一遍**。
//
//  以前进度存内存、进程一重启就没了，所以永远不会走到这里 ——
//  **这不是"新代码写错了"，是原有代码隐含假设了"进度会随进程消失"。**
//
//  ---------------------------------------------------------------------------
//  为什么"解锁状态"能推导、而"发过奖没有"不能
//  ---------------------------------------------------------------------------
//      "解锁了吗"  = 该成就的全部条件是否都 >= 需求  → **能从进度推导**
//      "发过奖吗"  = 一个**已经发生过的动作**        → **推导不出来，必须记账**
//
//  ⇒ 这是"状态"与"事件"的区别（同 M3-B 那条"**移动是状态、动作是事件**"）。
//     把发生过的事记下来，才不会重放它。
//
//  ---------------------------------------------------------------------------
//  ⚠️ 有了台账之后，"崩溃在中间"能自愈（这是它的第二个好处）
//  ---------------------------------------------------------------------------
//  进度落库与发奖是两步，中间可能崩。恢复后：
//
//      进度说"已达成" + 台账说"没发过"  → **应当发**（欠玩家一次）
//      进度说"已达成" + 台账说"发过了"  → **不重发**（已经给过）
//
//  ⇒ 只有"按次数/按顺序"记账才做不到这一点。**记"发过没有"天然幂等**。
//
//  ---------------------------------------------------------------------------
//  ⚠️ 名字里的历史遗留（与 `IQuestRewardSink` 同一族，但这次的结论**不一样**）
//  ---------------------------------------------------------------------------
//  它住在 `Game\Quest\` 下（和 `IQuestRewardSink` 一起），因为那是"奖励管道"两个接缝
//  的共同位置。但它**不是任务专用的** —— 所以类型名里**不带 `Quest`**：
//  这一片新加的接口，命名是免费的，那就一次说对（对照 `IQuestRewardSink` 改名要动 8 个文件）。
// ============================================================================

namespace NBC.Game.Quest
{
    /// <summary>奖励是"谁"发的（与数据库 `reward_granted.owner_kind` 一一对应）。</summary>
    public enum ERewardOwnerKind
    {
        /// <summary>任务（`Quest` 表）。</summary>
        Quest = 1,

        /// <summary>成就（`Achievement` 表）。</summary>
        Achievement = 2
    }

    /// <summary>
    /// 已发奖励台账：**回答"这份奖励发过没有"，并记下"刚刚发了"**。
    /// <para>⚠️ 实现必须**幂等**：同一个 `(kind, ownerId)` 重复 `MarkGranted` 不能报错、
    /// 也不能变成两条记录（数据库那边靠主键 `(player_id, owner_kind, owner_id)`）。</para>
    /// </summary>
    public interface IRewardLedger
    {
        /// <summary>这份奖励发过没有。</summary>
        /// <param name="kind">谁发的。</param>
        /// <param name="ownerId">发布者编号（任务编号 / 成就编号）。</param>
        /// <returns>发过返回 true。</returns>
        bool HasGranted(ERewardOwnerKind kind, int ownerId);

        /// <summary>记下"刚刚发了这份奖励"（**幂等**，重复调用无副作用）。</summary>
        /// <param name="kind">谁发的。</param>
        /// <param name="ownerId">发布者编号。</param>
        /// <param name="rewardId">奖励编号（留痕/排查用）。</param>
        void MarkGranted(ERewardOwnerKind kind, int ownerId, int rewardId);
    }
}
