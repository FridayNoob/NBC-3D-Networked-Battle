// ============================================================================
//  IConfigSource —— 配置资产的**来源接缝**
//  项目：3D联网战斗Demo   对应：CFG-R2（走 AB 而不是 Resources）、需求 8
//
//  ---------------------------------------------------------------------------
//  为什么要留这道缝（和 B2 的 `IAssetProvider`、E1 的 `IPerfCounterSource` 同一个套路）
//  ---------------------------------------------------------------------------
//  `ConfigMgr` 的职责是"**管缓存 + 提供查询**"，不是"怎么把文件读进来"。
//  把"从哪读"抽出去之后：
//
//      · EditMode 测试**不需要任何资产**，塞一个假来源就能验全部逻辑
//      · 真正的实现（走 YooAsset）等 **B4/B5 打包**做完再接，**一行都不用改 ConfigMgr**
//      · 以后要换来源（编辑器直接读 .asset / 服务端下发）也只加一个实现
//
//  ---------------------------------------------------------------------------
//  接口为什么用**回调**而不是 async/await
//  ---------------------------------------------------------------------------
//  和 A9 的 `UIManager` 同一条理由：`await` 的续体会被投递回
//  `UnitySynchronizationContext`，而 **EditMode 没有帧循环**，测试会卡死。
//  回调是"完成那一刻直接调用"，在 EditMode 里**确定性地**能跑。
//
//  ---------------------------------------------------------------------------
//  接口为什么**只给表名**、不给 Type
//  ---------------------------------------------------------------------------
//  加载器（YooAsset / 编辑器）要的是"**地址字符串**"（如 `HeroConfig`），
//  而不是 C# 类型。把 Type 塞进接口会把"资产系统"和"反射"绑在一起 ——
//  而类型那一侧的事 `ConfigMgr` 自己按命名约定就能推出来（`HeroConfig` ↔ `Hero`）。
// ============================================================================

using System;
using UnityEngine;

namespace NBC.Game.Config
{
    /// <summary>配置资产的来源：给一个表名，异步还一个 &lt;表&gt;Config 资产。</summary>
    public interface IConfigSource
    {
        /// <summary>来源描述（报错与日志里用，例如"YooAsset" / "假来源（测试）"）。</summary>
        string Description { get; }

        /// <summary>
        /// 加载一张表的配置资产。
        /// <para>
        /// ⚠️ **成功与失败都要回调**，且**只在主线程**回调一次。
        /// 两个都不回调会让调用方永远等下去 —— 那种 bug 极难查。
        /// </para>
        /// </summary>
        /// <param name="tableName">表名（如 `Hero`）；实现侧通常拿它拼资产地址。</param>
        /// <param name="onLoaded">成功：交出资产。</param>
        /// <param name="onFailed">失败：交出一句**人话**原因（不要丢一个异常堆栈给用户看）。</param>
        void LoadTable(string tableName, Action<ScriptableObject> onLoaded, Action<string> onFailed);
    }
}
