//  ELevelMode / EDamageType —— 配置表用到的枚举（**手写，不由工具生成**）
//  项目：3D联网战斗Demo   对应：Docs\17-配置表规范.md §二
//
//  ---------------------------------------------------------------------------
//  为什么枚举要手写
//  ---------------------------------------------------------------------------
//  规范里 `enum:类型名` 的语义是"**Exce 里写成员名，值由 C# 决定**"。
//  工具**不生成**枚举 —— 因为它不认识业务语义（谁是 Fire、谁是 Ice 是游戏设计）。
//  于是分工是：
//
//      Excel 侧：`damageType` 列写成员名（`Fire` / `Ice` / `Physical`）
//      C# 侧  ：就是下面这个枚举（**这是唯一权威来源**）
//      工具侧 ：只校验"这个成员名像标识符"，**不校验它真存在**
//
//  ⚠️ 最后一条是**如实记录的局限**：写错成员名（比如 `Fier`）工具查不出来，
//    要到生成的加载器 `Enum.Parse(..., true)` 运行时才炸。
//    想让工具提前查出来，把成员填进 `ConfigPolicy.KnownEnumMembers` 即可。
//
//  ⚠️ 成员名**大小写不敏感**地匹配（加载器用的是 `Enum.Parse(type, text, ignoreCase: true)`），
//    但建议在表里**照抄这里的写法**，别依赖容错。
// ============================================================================

namespace NBC.Game.Config
{
    /// <summary>伤害类型（配置表 <c>Skill.damageType</c> 用）。</summary>
    public enum EDamageType
    {
        /// <summary>物理。</summary>
        Physical = 0,

        /// <summary>火焰。</summary>
        Fire = 1,

        /// <summary>冰霜。</summary>
        Ice = 2
    }
}
