// ============================================================================
//  NBC.Framework.UI · UI 层级枚举
//  对应需求：FW-M09
//  缺陷编号：FW-10（UIManager 硬编码 UI 层路径）
//
//  ---------------------------------------------------------------------------
//  为什么这个枚举放在这里、而不是塞进 UIManager
//  ---------------------------------------------------------------------------
//  因为"有哪几层"是**UI 的公共词汇**：面板要知道自己能挂在哪，
//  加载遮罩要知道自己要被抬到最上面，业务层要指定"这个面板放哪"。
//  放在管理器里会让所有调用方都去依赖管理器。
//
//  ⚠️ **顺序有含义**：数值越大越靠前（渲染在越上层）。
//     `Bot` 在最底下（背景图、HUD），`System` 在最上面（弹窗、加载遮罩、断线提示）。
//     `UILayers` 组件靠这个顺序做人话报错，所以**不要随便调换顺序**。
// ============================================================================

namespace NBC.Framework.UI
{
    /// <summary>
    /// UI 层级。**数值越大越靠上层。**
    /// </summary>
    public enum UILayer
    {
        /// <summary>最底层：背景、主界面 HUD。</summary>
        Bot = 0,

        /// <summary>中间层：普通功能面板（背包、设置）。原框架的默认层。</summary>
        Mid = 1,

        /// <summary>上层：需要盖住普通面板的东西（角色详情、确认框）。</summary>
        Top = 2,

        /// <summary>最顶层：加载遮罩、断线提示、系统级弹窗。**永远盖在所有东西上面。**</summary>
        System = 3
    }
}
