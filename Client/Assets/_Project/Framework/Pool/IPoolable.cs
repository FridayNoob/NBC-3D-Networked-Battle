// 这个文件里有：
//   IPoolable（接口）：池化对象可选实现，让对象在取出 / 归还时自己复位内部状态

namespace NBC.Framework
{
    // 主要功能：给对象池一个可选钩子 —— 对象自己负责复位内部状态，池只在取出 / 归还的正确时机调用；不实现也能正常入池。
    // 主要数据成员：无字段，接口不持有状态，待复位的状态由实现方自己保存。
    // 主要外部方法：OnSpawned（取出时复位）、OnDespawned（归还时断开外部引用）。
    // 谁在用它：ObjectPool 的 Spawn / Release 按 as 判空后调用；实现方多在 Game / Boot 层（血条、特效等）。
    /// <summary>池化对象可选实现的接口：在取出 / 归还时复位自身状态；不实现也能正常入池。</summary>
    public interface IPoolable
    {
        // 功能：对象从池里取出、即将交给使用者时，把自身恢复到可用状态。
        // 入参：无
        // 返回：无
        // 步骤：无固定顺序，复位动作由实现方决定；必须在对象已记入使用中名单与计数之后执行，所以这里抛异常会让对象留在使用中。
        // 上游：ObjectPool.Spawn，在对象进入使用中名单与计数之后调用
        // 下游：实现方自己，例如血量回满、粒子重播、状态机复位
        // 注意：预热出来的闲置对象不进使用中名单，不会走这里；取出计数已先加，别指望在本钩子里改统计。
        /// <summary>从池中取出、即将交给使用者时调用，在这里把对象恢复到可用状态。</summary>
        void OnSpawned();

        // 功能：对象归还到池里、即将闲置时，断开外部引用、停掉协程、清掉临时数据。
        // 入参：无
        // 返回：无
        // 步骤：无固定顺序，清理动作由实现方决定；先于容量判断执行，所以对象可能在清理之后当场被销毁。
        // 上游：ObjectPool.Release 在对象移出使用中名单之后调用；重复归还或非本池对象会先报错返回，走不到这里
        // 下游：实现方自己，例如注销监听、停止协程、清临时数据
        // 注意：池满时归还也会先走这里再丢弃，不要假设清理完一定会被复用；Clear / Dispose 只销毁闲置对象、不回调本钩子，所以监听注销不能只放在这里。
        /// <summary>归还到池中、对象即将闲置时调用，在这里断开外部引用、停下协程、清掉临时数据。</summary>
        void OnDespawned();
    }
}
