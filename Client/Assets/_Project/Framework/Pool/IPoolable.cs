// ============================================================================
//  NBC.Framework · 池化对象可选接口
//  来源：为 M1-A2（ObjectPool）新增；对应需求文档 §7.1.2 FW-M04
//
//  为什么需要它？
//    "从池里取出"和"刚 new 出来"对使用者来说必须是同一件事。
//    但对象的【内部状态】往往不同：血条要回满、粒子要重播、状态机要复位。
//    这个接口就是把"复位"这件事交给对象自己实现，池只负责在正确的时机调用。
//
//  为什么是可选接口（而不是抽象基类）：
//    池要能装**任何**类型 —— 包括第三方类型（DOTween 的 Tweener、Unity 的 GameObject、
//    你自己的纯数据类）。强制继承基类会让这些类型根本进不了池。
//    接口 + `as` 判空，是"能装一切、又能在需要时挂钩子"的最小代价写法。
// ============================================================================

namespace NBC.Framework
{
    /// <summary>
    /// 池化对象可选实现的接口：用于在取出 / 归还时复位自身状态。
    /// 不实现也完全可以，池会照常工作。
    /// </summary>
    public interface IPoolable
    {
        /// <summary>
        /// 从池中取出、即将交给使用者时调用。
        /// 在这里把对象恢复到"可用"状态（血量回满、计时清零、监听挂上）。
        /// </summary>
        void OnSpawned();

        /// <summary>
        /// 归还到池中、对象即将闲置时调用。
        /// 在这里断开外部引用、停下协程、清掉临时数据（监听务必在这里注销）。
        /// </summary>
        void OnDespawned();
    }
}
