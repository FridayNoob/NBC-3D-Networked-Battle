// ============================================================================
//  NBC.Framework.Log · 日志输出目标（接缝）
//  对应需求：FW-M11（文件落盘）
//
//  ---------------------------------------------------------------------------
//  为什么要有这道缝
//  ---------------------------------------------------------------------------
//  `LogSystem` 只管"要不要记、记什么"，**不管记到哪去**。
//  于是：
//    · 落盘是 `FileLogSink`
//    · 控制台是 `UnityConsoleLogSink`
//    · **测试里是 `MemoryLogSink`** —— 断言"记了什么"不需要碰文件系统
//
//  这和 A8 的 `IAudioPlaybackProbe`、B2 的 `IAssetProvider` 是同一个手法：
//  **把不可控的环境（文件系统 / 设备 / 资源系统）变成可替换的实现。**
//
//  ⚠️ 但要说实话：这道缝**主要价值是测试与将来的扩展**（比如把日志发给服务端），
//     不是"将来一定要换实现"。不像 `IInputSource` 那样是明确的架构替换点。
// ============================================================================

namespace NBC.Framework.Log
{
    /// <summary>
    /// 日志的输出目标。
    /// </summary>
    public interface ILogSink
    {
        /// <summary>写一条。</summary>
        /// <param name="entry">日志条目。</param>
        void Write(in LogEntry entry);

        /// <summary>
        /// 把缓冲的内容刷出去。
        /// <para>退出前、崩溃前要调它，否则最后几条会丢。</para>
        /// </summary>
        void Flush();
    }
}
