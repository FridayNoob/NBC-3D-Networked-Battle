using UnityEngine;

namespace NBC.Framework.Audio
{
    /// <summary>
    /// 判断一个播放器"是否还在播"。
    /// </summary>
    public interface IAudioPlaybackProbe
    {
        /// <summary>
        /// 查询播放状态。
        /// </summary>
        /// <param name="source">目标播放器；**允许为 null / 已销毁**，实现必须能容忍。</param>
        /// <returns>true 表示还在播。</returns>
        bool IsPlaying(AudioSource source);
    }
}
